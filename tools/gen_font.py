rows = []
for c in range(128):
    ch = chr(c)
    g = G.get(ch)
    if g is None and 33 <= c < 127:
        g = G['?']
    if g is None:
        g = [" "] * 7
    cols = [0] * 5
    for r in range(7):
        line = (g[r] + " " * 7)[:7]
        for x in range(5):
            if line[x] == '#':
                cols[x] |= 1 << r
    rows.append("    { %s }, /* %s */" % (",".join("0x%02X" % v for v in cols),
                                          repr(ch)[1:-1] if ch != "'" else "'"))

out = ("/* font5x7.inc — generated by tools/gen_font.py\n"
       " * Classic public-domain 5x7 ASCII font.\n"
       " * FONT5X7[ascii][column]; bit0 = top pixel row. */\n"
       "static const uint8_t FONT5X7[128][5] = {\n"
       + "\n".join(rows) + "\n};\n")
open("main/ui/font5x7.inc", "w").write(out)
print("generated", len(rows), "glyphs")
